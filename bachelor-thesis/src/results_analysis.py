# Full results analysis pipeline

def run_results_analysis():
    """
    Main results analysis pipeline.

    Inputs:
    - results/model_metrics.csv

    Outputs:
    - thesis-ready tables in results/tables/
    - figures in results/figures/
    """
    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)

    print("Loading model metrics...")
    raw_metrics_df = load_metrics()

    print("Preparing metrics...")
    metrics_df = prepare_metrics(raw_metrics_df)

    print("Creating tables...")

    full_metrics_table = create_full_metrics_table(metrics_df)
    rmse_table = create_rmse_comparison_table(metrics_df)
    mae_table = create_mae_comparison_table(metrics_df)
    mda_table = create_directional_accuracy_table(metrics_df)
    r2_table = create_oos_r2_table(metrics_df)
    ranking_table = create_model_ranking_table(metrics_df)
    average_table = create_average_by_model_table(metrics_df)

    save_table(full_metrics_table, "full_metrics_table")
    save_table(rmse_table, "rmse_comparison_table")
    save_table(mae_table, "mae_comparison_table")
    save_table(mda_table, "directional_accuracy_table")
    save_table(r2_table, "oos_r2_table")
    save_table(ranking_table, "model_ranking_table")
    save_table(average_table, "average_by_model_table")

    print("Creating figures...")

    for asset_name in ASSET_ORDER:
        plot_id_vs_ood_metric(metrics_df, asset_name, "RMSE")
        plot_id_vs_ood_metric(metrics_df, asset_name, "MAE")
        plot_id_vs_ood_metric(metrics_df, asset_name, "MDA")
        plot_degradation(metrics_df, asset_name, "RMSE_Degradation_Pct")
        plot_degradation(metrics_df, asset_name, "MAE_Degradation_Pct")

    plot_average_rmse_by_model(metrics_df)
    plot_average_rmse_degradation(metrics_df)

    print("\nResults analysis completed successfully.")
    print(f"Tables saved to: {TABLES_DIR}")
    print(f"Figures saved to: {FIGURES_DIR}")

    return metrics_df


if __name__ == "__main__":
    run_results_analysis()