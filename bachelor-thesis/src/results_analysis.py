from pathlib import Path
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

# Project paths

PROJECT_ROOT = Path(__file__).resolve().parents[1]

RESULTS_DIR = PROJECT_ROOT / "results"
FIGURES_DIR = RESULTS_DIR / "figures"
TABLES_DIR = RESULTS_DIR / "tables"

METRICS_INPUT_PATH = RESULTS_DIR / "model_metrics.csv"

# Configuration

MODEL_ORDER = [
    "AR",
    "ARIMAX",
    "Ridge",
    "RandomForest",
    "MLP",
]

ASSET_ORDER = [
    "sp500",
    "nasdaq100",
]

REQUIRED_COLUMNS = [
    "asset",
    "model",
    "ID_MAE",
    "ID_RMSE",
    "ID_MDA",
    "ID_R2_OOS",
    "OOD_MAE",
    "OOD_RMSE",
    "OOD_MDA",
    "OOD_R2_OOS",
    "MAE_Degradation",
    "RMSE_Degradation",
]

NUMERIC_COLUMNS = [
    "ID_MAE",
    "ID_RMSE",
    "ID_MDA",
    "ID_R2_OOS",
    "OOD_MAE",
    "OOD_RMSE",
    "OOD_MDA",
    "OOD_R2_OOS",
    "MAE_Degradation",
    "RMSE_Degradation",
]

# Loading and validation

def load_metrics(path=METRICS_INPUT_PATH):
    """
    Load model_metrics.csv generated by experiments.py.
    """
    if not path.exists():
        raise FileNotFoundError(
            f"Metrics file not found: {path}. Run experiments.py first."
        )

    df = pd.read_csv(path)

    missing_columns = [
        col for col in REQUIRED_COLUMNS
        if col not in df.columns
    ]

    if missing_columns:
        raise ValueError(
            f"model_metrics.csv is missing required columns: {missing_columns}"
        )

    if df.empty:
        raise ValueError("model_metrics.csv is empty.")

    return df


def prepare_metrics(df):
    """
    Clean and enrich the metrics dataframe.

    Adds percentage versions of degradation metrics:
    - MAE_Degradation_Pct
    - RMSE_Degradation_Pct
    """
    df = df.copy()

    for col in NUMERIC_COLUMNS:
        df[col] = pd.to_numeric(df[col], errors="coerce")

    if df[NUMERIC_COLUMNS].isna().any().any():
        raise ValueError(
            "Some numeric metric columns contain invalid or missing values."
        )

    df["asset"] = pd.Categorical(
        df["asset"],
        categories=ASSET_ORDER,
        ordered=True
    )

    df["model"] = pd.Categorical(
        df["model"],
        categories=MODEL_ORDER,
        ordered=True
    )

    df = df.sort_values(["asset", "model"]).reset_index(drop=True)

    df["MAE_Degradation_Pct"] = df["MAE_Degradation"] * 100
    df["RMSE_Degradation_Pct"] = df["RMSE_Degradation"] * 100

    return df

# Table saving helpers

def save_table(df, filename):
    """
    Save a table as CSV and LaTeX.
    """
    TABLES_DIR.mkdir(parents=True, exist_ok=True)

    csv_path = TABLES_DIR / f"{filename}.csv"
    tex_path = TABLES_DIR / f"{filename}.tex"

    df.to_csv(csv_path, index=False)

    latex_df = df.copy()
    latex_df.to_latex(tex_path, index=False, float_format="%.6f")

    return csv_path, tex_path


def round_table(df, decimals=6):
    """
    Round numeric columns for cleaner thesis tables.
    """
    df = df.copy()

    numeric_cols = df.select_dtypes(include=["float", "int"]).columns

    for col in numeric_cols:
        df[col] = df[col].round(decimals)

    return df

# Thesis tables

def create_full_metrics_table(metrics_df):
    """
    Create the full model metrics table.
    """
    columns = [
        "asset",
        "model",
        "ID_MAE",
        "ID_RMSE",
        "ID_MDA",
        "ID_R2_OOS",
        "OOD_MAE",
        "OOD_RMSE",
        "OOD_MDA",
        "OOD_R2_OOS",
        "MAE_Degradation_Pct",
        "RMSE_Degradation_Pct",
    ]

    table = metrics_df[columns].copy()

    return round_table(table)


def create_rmse_comparison_table(metrics_df):
    """
    Create a table focused on RMSE stability and degradation.
    """
    columns = [
        "asset",
        "model",
        "ID_RMSE",
        "OOD_RMSE",
        "RMSE_Degradation_Pct",
    ]

    table = metrics_df[columns].copy()

    return round_table(table)


def create_mae_comparison_table(metrics_df):
    """
    Create a table focused on MAE stability and degradation.
    """
    columns = [
        "asset",
        "model",
        "ID_MAE",
        "OOD_MAE",
        "MAE_Degradation_Pct",
    ]

    table = metrics_df[columns].copy()

    return round_table(table)


def create_directional_accuracy_table(metrics_df):
    """
    Create a table focused on mean directional accuracy.
    """
    columns = [
        "asset",
        "model",
        "ID_MDA",
        "OOD_MDA",
    ]

    table = metrics_df[columns].copy()

    table["MDA_Change"] = table["OOD_MDA"] - table["ID_MDA"]

    return round_table(table)


def create_oos_r2_table(metrics_df):
    """
    Create a table focused on out-of-sample R2.
    """
    columns = [
        "asset",
        "model",
        "ID_R2_OOS",
        "OOD_R2_OOS",
    ]

    table = metrics_df[columns].copy()

    table["R2_OOS_Change"] = table["OOD_R2_OOS"] - table["ID_R2_OOS"]

    return round_table(table)


def create_model_ranking_table(metrics_df):
    """
    Create ranking table.

    Lower OOD_RMSE is better.
    Lower RMSE_Degradation_Pct is better.
    """
    table = metrics_df[
        [
            "asset",
            "model",
            "OOD_RMSE",
            "RMSE_Degradation_Pct",
        ]
    ].copy()

    table["OOD_RMSE_Rank"] = (
        table.groupby("asset", observed=False)["OOD_RMSE"]
        .rank(method="dense", ascending=True)
        .astype(int)
    )

    table["Robustness_Rank"] = (
        table.groupby("asset", observed=False)["RMSE_Degradation_Pct"]
        .rank(method="dense", ascending=True)
        .astype(int)
    )

    table = table.sort_values(
        ["asset", "OOD_RMSE_Rank", "Robustness_Rank"]
    ).reset_index(drop=True)

    return round_table(table)


def create_average_by_model_table(metrics_df):
    """
    Average metrics across S&P 500 and NASDAQ-100.

    This is useful as a compact summary, but the asset-level results
    should remain the main evidence.
    """
    table = (
        metrics_df
        .groupby("model", observed=False)
        .agg(
            Average_ID_RMSE=("ID_RMSE", "mean"),
            Average_OOD_RMSE=("OOD_RMSE", "mean"),
            Average_RMSE_Degradation_Pct=("RMSE_Degradation_Pct", "mean"),
            Average_ID_MAE=("ID_MAE", "mean"),
            Average_OOD_MAE=("OOD_MAE", "mean"),
            Average_MAE_Degradation_Pct=("MAE_Degradation_Pct", "mean"),
        )
        .reset_index()
    )

    table = table.sort_values("Average_OOD_RMSE").reset_index(drop=True)

    return round_table(table)

# Plot helpers

def save_figure(fig, filename):
    """
    Save a matplotlib figure.
    """
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)

    output_path = FIGURES_DIR / filename

    fig.savefig(output_path, dpi=300, bbox_inches="tight")
    plt.close(fig)

    return output_path


def plot_id_vs_ood_metric(metrics_df, asset_name, metric_name):
    """
    Plot ID vs OOD comparison for one metric.

    metric_name should be one of:
    - MAE
    - RMSE
    - MDA
    - R2_OOS
    """
    subset = metrics_df[metrics_df["asset"] == asset_name].copy()
    subset = subset.sort_values("model")

    models = subset["model"].astype(str).values
    id_values = subset[f"ID_{metric_name}"].values
    ood_values = subset[f"OOD_{metric_name}"].values

    x = np.arange(len(models))
    width = 0.35

    fig, ax = plt.subplots(figsize=(10, 5))

    ax.bar(x - width / 2, id_values, width, label="ID test")
    ax.bar(x + width / 2, ood_values, width, label="OOD test")

    ax.set_title(f"{asset_name.upper()} {metric_name}: ID vs OOD")
    ax.set_xlabel("Model")
    ax.set_ylabel(metric_name)
    ax.set_xticks(x)
    ax.set_xticklabels(models, rotation=30, ha="right")
    ax.legend()
    ax.grid(axis="y", alpha=0.3)

    fig.tight_layout()

    filename = f"{asset_name}_{metric_name.lower()}_id_vs_ood.png"

    return save_figure(fig, filename)


def plot_degradation(metrics_df, asset_name, degradation_column):
    """
    Plot degradation percentage for one asset.

    degradation_column should be:
    - MAE_Degradation_Pct
    - RMSE_Degradation_Pct
    """
    subset = metrics_df[metrics_df["asset"] == asset_name].copy()
    subset = subset.sort_values("model")

    models = subset["model"].astype(str).values
    values = subset[degradation_column].values

    x = np.arange(len(models))

    fig, ax = plt.subplots(figsize=(10, 5))

    ax.bar(x, values)

    readable_name = degradation_column.replace("_", " ")

    ax.set_title(f"{asset_name.upper()} {readable_name}")
    ax.set_xlabel("Model")
    ax.set_ylabel("Degradation (%)")
    ax.set_xticks(x)
    ax.set_xticklabels(models, rotation=30, ha="right")
    ax.axhline(0, linewidth=1)
    ax.grid(axis="y", alpha=0.3)

    fig.tight_layout()

    filename = f"{asset_name}_{degradation_column.lower()}.png"

    return save_figure(fig, filename)


